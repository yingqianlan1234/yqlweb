const context = vm.createContext({ Date, Math, Number });
vm.runInContext(source.slice(source.indexOf('const DAY_MS'), source.indexOf('function setDisclosure')) +
  ';this.api = { birthdayInfo, normalizeLocation, normalizeWeather, weatherDescription, claimBirthdayCelebration, clampBirthday };', context);
const { birthdayInfo, normalizeLocation, normalizeWeather, weatherDescription, claimBirthdayCelebration, clampBirthday } = context.api;
assert.equal(birthdayInfo('2000-10-16', new Date(2026, 9, 16)).today, true);
